-- 1. Terminals Table
CREATE TABLE IF NOT EXISTS terminals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    terminal_id VARCHAR(255) NOT NULL UNIQUE,
    terminal_name VARCHAR(255) NOT NULL,
    device_identifier VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    secret_key VARCHAR(255),
    authorized_by_user_id BIGINT REFERENCES users(id) ON DELETE NO ACTION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_terminals_restaurant ON terminals(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_terminals_terminal_id ON terminals(terminal_id);
CREATE INDEX IF NOT EXISTS idx_terminals_status ON terminals(status);

-- 2. Terminal Pairing Codes Table
CREATE TABLE IF NOT EXISTS terminal_pairing_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
    terminal_name VARCHAR(255),
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    consumed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    consumed_by_terminal_id BIGINT REFERENCES terminals(id) ON DELETE NO ACTION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_pairing_codes_code ON terminal_pairing_codes(code);
CREATE INDEX IF NOT EXISTS idx_pairing_codes_restaurant ON terminal_pairing_codes(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_pairing_codes_consumed ON terminal_pairing_codes(consumed);
