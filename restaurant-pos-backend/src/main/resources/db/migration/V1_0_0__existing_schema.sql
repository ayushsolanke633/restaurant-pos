-- Flyway Migration: V1_0_0__existing_schema.sql
-- Description: Baseline schema definition for fresh database installations.
--
-- IMPORTANT OPERATIONAL NOTE:
-- On an existing populated database (such as restaurant_pos), Flyway is configured
-- with baseline-on-migrate=true at baseline-version=1.0.0.
-- Consequently, Flyway will record this version as the BASELINE and will NOT execute
-- this script against the existing database.
--
-- On a genuinely fresh database, Flyway executes this script to initialize all 16
-- required application tables and seed global roles, before subsequent migrations
-- (such as V1_1_0) are applied.
--
-- All foreign keys preserve existing PostgreSQL schema behavior: ON DELETE NO ACTION.
-- ==============================================================================

-- 1. Global Role Table
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

-- Seed global roles (ADMIN, WAITER, KITCHEN)
INSERT INTO roles (id, name) VALUES
    (1, 'ADMIN'),
    (2, 'WAITER'),
    (3, 'KITCHEN');

-- Ensure subsequent identity values start after explicit seed IDs
ALTER TABLE roles ALTER COLUMN id RESTART WITH 4;

-- 2. Restaurant Table (Tenant Root)
CREATE TABLE restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address TEXT,
    phone VARCHAR(255),
    email VARCHAR(255),
    gst_number VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 3. User Table
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE NO ACTION,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(255),
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 4. Restaurant Tables
CREATE TABLE restaurant_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    table_number INTEGER NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 5. Categories
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 6. Menu Items
CREATE TABLE menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE NO ACTION,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    price NUMERIC(10,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 7. Customers
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    email VARCHAR(255),
    address TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 8. Orders
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    table_id BIGINT REFERENCES restaurant_tables(id) ON DELETE NO ACTION,
    customer_id BIGINT REFERENCES customers(id) ON DELETE NO ACTION,
    waiter_id BIGINT REFERENCES users(id) ON DELETE NO ACTION,
    order_type VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    tax_amount NUMERIC(10,2) NOT NULL,
    discount_amount NUMERIC(10,2) NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 9. Order Items (Child of Order)
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE NO ACTION,
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE NO ACTION,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 10. Bills
CREATE TABLE bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE NO ACTION,
    bill_number VARCHAR(255) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    tax_amount NUMERIC(10,2) NOT NULL,
    discount_amount NUMERIC(10,2) NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL,
    generated_by BIGINT NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_bills_restaurant_bill_number UNIQUE (restaurant_id, bill_number),
    CONSTRAINT uk_bills_order_id UNIQUE (order_id)
);

-- 11. Payments (Child of Bill)
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES bills(id) ON DELETE NO ACTION,
    amount NUMERIC(10,2) NOT NULL,
    payment_method VARCHAR(255) NOT NULL,
    payment_status VARCHAR(255) NOT NULL,
    transaction_reference VARCHAR(255),
    paid_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 12. Inventory Items
CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    name VARCHAR(255) NOT NULL,
    unit VARCHAR(255) NOT NULL,
    current_quantity NUMERIC(12,3) NOT NULL,
    minimum_quantity NUMERIC(12,3) NOT NULL,
    cost_per_unit NUMERIC(10,2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_inventory_items_restaurant_name UNIQUE (restaurant_id, name)
);

-- 13. Inventory Transactions (Child of InventoryItem)
CREATE TABLE inventory_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_item_id BIGINT NOT NULL REFERENCES inventory_items(id) ON DELETE NO ACTION,
    type VARCHAR(255) NOT NULL,
    quantity NUMERIC(12,3) NOT NULL,
    reference_type VARCHAR(255),
    reference_id BIGINT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 14. Restaurant Settings
CREATE TABLE restaurant_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION UNIQUE,
    tax_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    default_tax_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    service_charge_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    default_service_charge_rate NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    timezone VARCHAR(100) NOT NULL DEFAULT 'Asia/Kolkata',
    receipt_header TEXT,
    receipt_footer TEXT,
    invoice_prefix VARCHAR(20) NOT NULL DEFAULT 'INV',
    auto_accept_orders BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_restaurant_settings_restaurant_id UNIQUE (restaurant_id)
);

-- 15. Order Status History (Child of Order)
CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE NO ACTION,
    status VARCHAR(255) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

-- 16. Notifications
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE NO ACTION,
    recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
    type VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT,
    reference_type VARCHAR(255),
    reference_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);
